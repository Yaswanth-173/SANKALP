export const ALL_CATEGORIES = CONTRACTOR_GROUPS.flatMap((g) => g.categories.map((c) => ({ ...c, groupId: g.id, groupLabel: g.label })))

export function findCategoryBySlug(slug) {
  if (slug === FULL_HOUSE.slug) return FULL_HOUSE
  return ALL_CATEGORIES.find((c) => c.slug === slug) || null
}

export function findCategoryByName(name) {
  if (name === FULL_HOUSE.name) return FULL_HOUSE
  return ALL_CATEGORIES.find((c) => c.name === name) || null
}

export const CART_DEAL_NOTES = ['Added from Contractor Categories', 'Complete home construction package requested']

// dealNote may have a specific team member appended (e.g. "<base> — Requested: Akash Rao (Plumbing Engineer)"),
// so cart-membership checks match by prefix, not exact equality.
export function isCartDealNote(dealNote) {
  if (!dealNote) return false
  return CART_DEAL_NOTES.some((base) => dealNote.startsWith(base))
}
